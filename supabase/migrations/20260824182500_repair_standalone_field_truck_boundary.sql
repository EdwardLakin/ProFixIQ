create table if not exists private.field_service_vehicle_assignment_quarantine (
  id bigint generated by default as identity primary key,
  shop_id uuid not null,
  service_vehicle_id uuid not null,
  profile_id uuid not null,
  assigned_by_profile_id uuid,
  assignment_created_at timestamptz not null,
  assignment_updated_at timestamptz not null,
  reason text not null check (
    reason in (
      'non_canonical_profile',
      'missing_owner_vehicle',
      'ambiguous_owner_vehicle_set',
      'assigned_vehicle_not_unique_owner_vehicle'
    )
  ),
  source_migration text not null default
    '20260824182500_repair_standalone_field_truck_boundary',
  quarantined_at timestamptz not null default now(),
  unique (
    shop_id,
    service_vehicle_id,
    profile_id,
    assignment_updated_at,
    reason
  )
);

revoke all on table private.field_service_vehicle_assignment_quarantine
  from public, anon, authenticated, service_role;

comment on table private.field_service_vehicle_assignment_quarantine is
  'Observable snapshots of standalone Field truck assignments removed because they were ambiguous, non-canonical, or mismatched.';

create or replace function private.repair_standalone_field_vehicle_assignments()
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_quarantined integer := 0;
  v_deleted integer := 0;
  v_assigned integer := 0;
begin
  with canonical_owners as materialized (
    select
      workspace.id as shop_id,
      owner_profile.id as profile_id
    from public.shops workspace
    join lateral (
      select profile.id
      from public.profiles profile
      where profile.shop_id = workspace.id
        and workspace.owner_id in (profile.id, profile.user_id)
      order by (profile.id = workspace.owner_id) desc, profile.id
      limit 1
    ) owner_profile on true
    where workspace.subscription_package = 'field_service'
  ),
  owner_vehicle_state as materialized (
    select
      owner.shop_id,
      owner.profile_id,
      count(vehicle.id) filter (
        where vehicle.active
          and coalesce(vehicle.capabilities, '{}'::jsonb)
            @> '{"mobile_v1":true}'::jsonb
      )::integer as eligible_vehicle_count,
      (
        array_agg(vehicle.id order by vehicle.created_at, vehicle.id) filter (
          where vehicle.active
            and coalesce(vehicle.capabilities, '{}'::jsonb)
              @> '{"mobile_v1":true}'::jsonb
        )
      )[1] as unique_vehicle_id
    from canonical_owners owner
    left join public.service_vehicles vehicle
      on vehicle.shop_id = owner.shop_id
     and vehicle.primary_user_id = owner.profile_id
    group by owner.shop_id, owner.profile_id
  ),
  classified as materialized (
    select
      assignment.shop_id,
      assignment.service_vehicle_id,
      assignment.profile_id,
      assignment.assigned_by_profile_id,
      assignment.created_at,
      assignment.updated_at,
      case
        when owner.profile_id is null
          or assignment.profile_id is distinct from owner.profile_id
          then 'non_canonical_profile'
        when coalesce(state.eligible_vehicle_count, 0) = 0
          then 'missing_owner_vehicle'
        when state.eligible_vehicle_count > 1
          then 'ambiguous_owner_vehicle_set'
        when assignment.service_vehicle_id is distinct from state.unique_vehicle_id
          then 'assigned_vehicle_not_unique_owner_vehicle'
        else null
      end as reason
    from public.field_service_vehicle_assignments assignment
    join public.shops workspace
      on workspace.id = assignment.shop_id
     and workspace.subscription_package = 'field_service'
    left join canonical_owners owner
      on owner.shop_id = assignment.shop_id
    left join owner_vehicle_state state
      on state.shop_id = assignment.shop_id
     and state.profile_id = owner.profile_id
  ),
  invalid as materialized (
    select *
    from classified
    where reason is not null
  ),
  quarantined as (
    insert into private.field_service_vehicle_assignment_quarantine (
      shop_id,
      service_vehicle_id,
      profile_id,
      assigned_by_profile_id,
      assignment_created_at,
      assignment_updated_at,
      reason
    )
    select
      invalid.shop_id,
      invalid.service_vehicle_id,
      invalid.profile_id,
      invalid.assigned_by_profile_id,
      invalid.created_at,
      invalid.updated_at,
      invalid.reason
    from invalid
    on conflict do nothing
    returning 1
  ),
  deleted as (
    delete from public.field_service_vehicle_assignments assignment
    using invalid
    where assignment.shop_id = invalid.shop_id
      and assignment.service_vehicle_id = invalid.service_vehicle_id
      and assignment.profile_id = invalid.profile_id
    returning 1
  )
  select
    coalesce((select count(*) from quarantined), 0),
    coalesce((select count(*) from deleted), 0)
  into v_quarantined, v_deleted;

  with canonical_owners as materialized (
    select
      workspace.id as shop_id,
      owner_profile.id as profile_id
    from public.shops workspace
    join lateral (
      select profile.id
      from public.profiles profile
      where profile.shop_id = workspace.id
        and workspace.owner_id in (profile.id, profile.user_id)
      order by (profile.id = workspace.owner_id) desc, profile.id
      limit 1
    ) owner_profile on true
    where workspace.subscription_package = 'field_service'
  ),
  owner_vehicle_state as materialized (
    select
      owner.shop_id,
      owner.profile_id,
      count(vehicle.id) filter (
        where vehicle.active
          and coalesce(vehicle.capabilities, '{}'::jsonb)
            @> '{"mobile_v1":true}'::jsonb
      )::integer as eligible_vehicle_count,
      (
        array_agg(vehicle.id order by vehicle.created_at, vehicle.id) filter (
          where vehicle.active
            and coalesce(vehicle.capabilities, '{}'::jsonb)
              @> '{"mobile_v1":true}'::jsonb
        )
      )[1] as unique_vehicle_id
    from canonical_owners owner
    left join public.service_vehicles vehicle
      on vehicle.shop_id = owner.shop_id
     and vehicle.primary_user_id = owner.profile_id
    group by owner.shop_id, owner.profile_id
  )
  insert into public.field_service_vehicle_assignments (
    shop_id,
    service_vehicle_id,
    profile_id,
    assigned_by_profile_id
  )
  select
    state.shop_id,
    state.unique_vehicle_id,
    state.profile_id,
    state.profile_id
  from owner_vehicle_state state
  where state.eligible_vehicle_count = 1
    and state.unique_vehicle_id is not null
    and not exists (
      select 1
      from public.field_service_vehicle_assignments assignment
      where assignment.shop_id = state.shop_id
        and (
          assignment.profile_id = state.profile_id
          or assignment.service_vehicle_id = state.unique_vehicle_id
        )
    )
  on conflict do nothing;

  get diagnostics v_assigned = row_count;

  return jsonb_build_object(
    'quarantined', v_quarantined,
    'deleted', v_deleted,
    'assigned', v_assigned
  );
end;
$$;

revoke all on function private.repair_standalone_field_vehicle_assignments()
  from public, anon, authenticated, service_role;

-- Field entitlement is a product/workspace decision. A canonical standalone
-- owner remains entitled even when My Truck data is ambiguous and must be
-- repaired separately.
create or replace function public.mobile_profile_has_field_service_access(
  p_shop_id uuid,
  p_profile_id uuid
) returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select public.profixiq_shop_has_product_access(
      p_shop_id,
      'field_service'
    )
    and exists (
      select 1
      from public.mobile_service_settings settings
      join public.mobile_field_operators operator
        on operator.shop_id = settings.shop_id
       and operator.profile_id = p_profile_id
       and operator.enabled
      join public.profiles profile
        on profile.id = operator.profile_id
       and profile.shop_id = settings.shop_id
      join public.shops workspace
        on workspace.id = settings.shop_id
      where settings.shop_id = p_shop_id
        and settings.onboarding_completed_at is not null
        and settings.service_model in ('mobile', 'both')
        and (
          workspace.subscription_package is distinct from 'field_service'
          or (
            workspace.owner_id in (profile.id, profile.user_id)
          )
        )
    );
$$;

revoke all on function public.mobile_profile_has_field_service_access(uuid, uuid)
  from public, anon, authenticated;
grant execute on function public.mobile_profile_has_field_service_access(uuid, uuid)
  to service_role;

-- Truck access is narrower than Field entitlement. A standalone assignment is
-- valid only when it points at the canonical owner's sole active Mobile V1
-- vehicle. Shop-linked Field preserves its established explicit-assignment
-- behavior.
create or replace function public.field_actor_can_access_service_vehicle(
  p_shop_id uuid,
  p_service_vehicle_id uuid
) returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.field_service_vehicle_assignments assignment
    join public.profiles profile
      on profile.id = assignment.profile_id
     and profile.shop_id = assignment.shop_id
    join public.shops workspace
      on workspace.id = assignment.shop_id
    join public.service_vehicles vehicle
      on vehicle.id = assignment.service_vehicle_id
     and vehicle.shop_id = assignment.shop_id
     and vehicle.active
     and coalesce(vehicle.capabilities, '{}'::jsonb)
       @> '{"mobile_v1":true}'::jsonb
    where assignment.shop_id = p_shop_id
      and assignment.service_vehicle_id = p_service_vehicle_id
      and (profile.id = auth.uid() or profile.user_id = auth.uid())
      and public.mobile_profile_has_field_service_access(
        profile.shop_id,
        profile.id
      )
      and (
        workspace.subscription_package is distinct from 'field_service'
        or (
          workspace.owner_id in (profile.id, profile.user_id)
          and vehicle.primary_user_id = profile.id
          and (
            select count(*)
            from public.service_vehicles candidate
            where candidate.shop_id = workspace.id
              and candidate.primary_user_id = profile.id
              and candidate.active
              and coalesce(candidate.capabilities, '{}'::jsonb)
                @> '{"mobile_v1":true}'::jsonb
          ) = 1
        )
      )
  );
$$;

revoke all on function public.field_actor_can_access_service_vehicle(uuid, uuid)
  from public, anon;
grant execute on function public.field_actor_can_access_service_vehicle(uuid, uuid)
  to authenticated, service_role;

select private.repair_standalone_field_vehicle_assignments();

comment on function private.repair_standalone_field_vehicle_assignments() is
